"""Single source of truth for Moon geometry exports.

Builds a pyproj Transformer from a supplied Moon raster's own CRS (its
geodetic CRS to its projected CRS, always_xy=True). The spherical Moon radius
is read from the raster CRS and must be 1,737,400 m; no Earth ellipsoid is
used and no projection string is hardcoded.

Outputs (regenerated by this script, never hand-edited):
  web/data/moon/regions.json - per region: id, name, center and polygon in
                               projection meters AND in lat/lon.
  web/data/moon/layers.json  - per layer (backdrop and each site's hillshade,
                               slope, hazard, support): bounds in projection
                               meters computed from the GeoTIFF edges. When a
                               raster reports AREA_OR_POINT=Point, a
                               half-pixel outward correction is applied; when
                               Area (all current files), the geotransform
                               edges are already correct.

Usage: python scripts/moon_geo.py
Prints a per-region lat/lon -> meters -> lat/lon round-trip table; every error
must be under 0.01 m or the script exits nonzero.
"""

import json
import math
import sys
from pathlib import Path

import numpy as np
import pyproj
import rasterio

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw" / "moon"
PROCESSED_DIR = ROOT / "data" / "processed" / "moon"
WEB_DIR = ROOT / "web" / "data" / "moon"

REGIONS_FILE = "A3_Named_regions_SP.geojson"
BACKDROP_FILE = "LDRM_80S_1000MPP_ADJ_ROUGH_100M.tiff"
REFERENCE_RASTER = "site_01_final_adj_5mpp_surf.tif"

# site ids -> GeoJSON region ids (site_04 has no GeoJSON region; see below).
REGION_SITE_KEYS = {5: "sl3", 6: "site_01", 8: "site_07"}
SITE_LABELS = {
    "site_01": "Connecting Ridge",
    "site_04": "Shackleton Rim (raster site_04; not in the A3 regions file)",
    "site_07": "Peak Near Shakleton",
    "sl3": "Connecting Ridge Extension",
}
SITE_LAYERS = {
    # layer name -> processed GeoTIFF that defines its placement
    "hillshade": "elevation.tif",
    "slope": "slope.tif",
    "hazard": "hazard.tif",
    "support": "support.tif",
}
SITE_LAYER_IMAGES = {
    "hillshade": "hillshade.png",
    "slope": "slope.png",
    "hazard": "hazard.png",
    "support": "support.png",
}
EXPECTED_RADIUS_M = 1_737_400.0


def load_transformer(raster_path: Path):
    """Build the pyproj transformer from the raster's own CRS."""
    with rasterio.open(raster_path) as source:
        crs = source.crs
    if crs is None:
        raise ValueError(f"{raster_path.name} has no embedded CRS")
    projected = pyproj.CRS.from_user_input(crs)
    geodetic = projected.geodetic_crs
    if geodetic is None:
        raise ValueError(f"{raster_path.name} CRS has no geodetic CRS")
    ellipsoid = geodetic.ellipsoid
    if ellipsoid is None or not math.isclose(
        ellipsoid.semi_major_metre, EXPECTED_RADIUS_M, rel_tol=1e-9
    ):
        raise ValueError(
            f"{raster_path.name} CRS radius is "
            f"{ellipsoid.semi_major_metre if ellipsoid else None} m; "
            f"expected the {EXPECTED_RADIUS_M} m spherical Moon"
        )
    transformer = pyproj.Transformer.from_crs(
        geodetic, projected, always_xy=True
    )
    inverse = pyproj.Transformer.from_crs(projected, geodetic, always_xy=True)
    return transformer, inverse, projected


class MoonGeometry:
    """lon/lat <-> projection meters conversions for one raster CRS."""

    def __init__(self, raster_path: Path):
        self.forward, self.inverse, self.crs = load_transformer(raster_path)
        self.crs_wkt = self.crs.to_wkt()

    def lonlat_to_xy(self, longitude: float, latitude: float):
        x, y = self.forward.transform(longitude, latitude)
        return float(x), float(y)

    def xy_to_lonlat(self, x: float, y: float):
        longitude, latitude = self.inverse.transform(x, y)
        return float(longitude), float(latitude)

    def round_trip_error_m(self, longitude: float, latitude: float) -> float:
        x, y = self.lonlat_to_xy(longitude, latitude)
        back_lon, back_lat = self.xy_to_lonlat(x, y)
        return math.hypot(
            math.radians(back_lat - latitude) * EXPECTED_RADIUS_M,
            math.radians(back_lon - longitude) * EXPECTED_RADIUS_M
            * math.cos(math.radians(latitude)),
        )


def raster_edges(path: Path) -> dict:
    """Edge bounds in projection meters, honoring AREA_OR_POINT."""
    with rasterio.open(path) as source:
        transform = source.transform
        area_or_point = source.tags().get("AREA_OR_POINT", "Area")
        width, height = source.width, source.height
        crs_name = (source.crs.to_string() if source.crs else "NONE")
    left = transform.c
    top = transform.f
    pixel_x = transform.a
    pixel_y = transform.e
    right = left + pixel_x * width
    bottom = top + pixel_y * height
    corrected = False
    if area_or_point == "Point":
        # Geotransform refers to sample centers; push edges out half a pixel.
        left -= pixel_x / 2
        right += pixel_x / 2
        top -= pixel_y / 2
        bottom += pixel_y / 2
        corrected = True
    return {
        "raster": str(path.relative_to(ROOT)),
        "crs_name": crs_name,
        "area_or_point": area_or_point,
        "half_pixel_correction_applied": corrected,
        "pixel_size_m": {"x": abs(pixel_x), "y": abs(pixel_y)},
        "shape": [int(height), int(width)],
        "bounds_m": {
            "min_x": left, "min_y": bottom, "max_x": right, "max_y": top,
        },
    }


def polygon_lonlat_to_xy(geometry, moon: MoonGeometry):
    return [
        [[*moon.lonlat_to_xy(float(lon), float(lat))]
         for lon, lat, *_ in ring]
        for ring in geometry["coordinates"]
    ]


def polygon_xy_to_lonlat(rings_xy, moon: MoonGeometry):
    return [
        [[*moon.xy_to_lonlat(float(x), float(y))]
         for x, y in ring]
        for ring in rings_xy
    ]


def ring_centroid(ring_xy):
    points = ring_xy[:-1] if ring_xy[0] == ring_xy[-1] else ring_xy
    xs = [float(p[0]) for p in points]
    ys = [float(p[1]) for p in points]
    return sum(xs) / len(xs), sum(ys) / len(ys)


def build_regions(moon: MoonGeometry, geojson: dict) -> list:
    features = []
    for feature in geojson["features"]:
        region_id = feature.get("id", feature.get("properties", {}).get("id"))
        name = feature["properties"]["label"]
        site_key = REGION_SITE_KEYS.get(region_id)
        rings_xy = polygon_lonlat_to_xy(feature["geometry"], moon)
        center_x, center_y = ring_centroid(rings_xy[0])
        center_lon, center_lat = moon.xy_to_lonlat(center_x, center_y)
        features.append({
            "type": "Feature",
            "id": region_id,
            "properties": {
                "name": name,
                "source": "A3_Named_regions_SP.geojson",
                "in_a3_regions_file": True,
                "site_key": site_key,
                "has_elevation_data": site_key is not None,
                "center_xy": [center_x, center_y],
                "center_lonlat": [center_lon, center_lat],
            },
            "geometry": {
                "type": "Polygon",
                "coordinates": rings_xy,
            },
            "geometry_lonlat": {
                "type": "Polygon",
                "coordinates": feature["geometry"]["coordinates"],
            },
        })

    # site_04 has no GeoJSON feature; its region outline is the supplied
    # raster footprint, and the label discloses that it is not in the file.
    footprint = raster_edges(RAW_DIR / "site_04_final_adj_5mpp_surf.tif")
    bounds = footprint["bounds_m"]
    corners_xy = [
        [bounds["min_x"], bounds["min_y"]],
        [bounds["max_x"], bounds["min_y"]],
        [bounds["max_x"], bounds["max_y"]],
        [bounds["min_x"], bounds["max_y"]],
        [bounds["min_x"], bounds["min_y"]],
    ]
    corners_lonlat = [
        [*moon.xy_to_lonlat(float(x), float(y))] for x, y in corners_xy
    ]
    center_x, center_y = ring_centroid(corners_xy)
    center_lon, center_lat = moon.xy_to_lonlat(center_x, center_y)
    features.append({
        "type": "Feature",
        "id": "site_04",
        "properties": {
            "name": SITE_LABELS["site_04"],
            "source": "site_04_final_adj_5mpp_surf.tif footprint",
            "in_a3_regions_file": False,
            "site_key": "site_04",
            "has_elevation_data": True,
            "center_xy": [center_x, center_y],
            "center_lonlat": [center_lon, center_lat],
        },
        "geometry": {
            "type": "Polygon",
            "coordinates": [corners_xy],
        },
        "geometry_lonlat": {
            "type": "Polygon",
            "coordinates": [corners_lonlat],
        },
    })
    return features


def build_layers(moon: MoonGeometry) -> dict:
    backdrop = raster_edges(RAW_DIR / BACKDROP_FILE)
    site_layers = {}
    for site_key in ("site_01", "site_04", "site_07", "sl3"):
        entries = {}
        for layer, tif_name in SITE_LAYERS.items():
            path = PROCESSED_DIR / site_key / tif_name
            if not path.exists():
                raise FileNotFoundError(
                    f"missing processed GeoTIFF for {site_key} {layer}: {path}"
                )
            entry = raster_edges(path)
            entry["image"] = (
                f"data/processed/moon/{site_key}/{SITE_LAYER_IMAGES[layer]}"
            )
            entries[layer] = entry
        site_layers[site_key] = entries
    return {
        "coordinate_system": "Moon south polar stereographic meters",
        "radius_m": EXPECTED_RADIUS_M,
        "crs_source": f"data/raw/moon/{REFERENCE_RASTER}",
        "crs_wkt": moon.crs_wkt,
        "backdrop": {
            **backdrop,
            "image": "web/data/moon/roughness_backdrop.png",
            "image_resolution_m": 2000,
            "data_status": "REAL - NASA LOLA roughness product; context only",
        },
        "sites": site_layers,
    }


def main() -> None:
    moon = MoonGeometry(RAW_DIR / REFERENCE_RASTER)

    # Authoritative cross-check: reproduce the gdalinfo-reported geographic
    # corner of the reference raster (136d28'07.68"W, 89d05'25.02"S) from its
    # projected lower-left corner.
    lon, lat = moon.xy_to_lonlat(-19000.0, -20000.0)
    expected_lon = -(136 + 28 / 60 + 7.68 / 3600)
    expected_lat = -(89 + 5 / 60 + 25.02 / 3600)
    corner_error = math.hypot(
        (lon - expected_lon) * math.cos(math.radians(lat))
        * math.pi / 180 * EXPECTED_RADIUS_M,
        (lat - expected_lat) * math.pi / 180 * EXPECTED_RADIUS_M,
    )
    if corner_error > 1.0:
        raise ValueError(
            f"pyproj transformer disagrees with the raster's own geographic "
            f"corner by {corner_error:.3f} m"
        )
    print(
        f"transformer: {moon.crs.name} geodetic->projected from "
        f"{REFERENCE_RASTER}; gdalinfo corner match {corner_error:.3f} m"
    )

    geojson = json.loads((RAW_DIR / REGIONS_FILE).read_text())
    features = build_regions(moon, geojson)
    regions_document = {
        "type": "FeatureCollection",
        "coordinate_system": "Moon south polar stereographic meters",
        "radius_m": EXPECTED_RADIUS_M,
        "crs_source": f"data/raw/moon/{REFERENCE_RASTER}",
        "features": features,
    }
    (WEB_DIR / "regions.json").write_text(
        json.dumps(regions_document, indent=2) + "\n"
    )

    layers_document = build_layers(moon)
    (WEB_DIR / "layers.json").write_text(
        json.dumps(layers_document, indent=2) + "\n"
    )

    print(f"regions: {len(features)} features -> web/data/moon/regions.json")
    print("layer bounds -> web/data/moon/layers.json")
    for site_key, entries in layers_document["sites"].items():
        b = entries["hillshade"]["bounds_m"]
        print(
            f"  {site_key}: x {b['min_x']:.0f}..{b['max_x']:.0f}, "
            f"y {b['min_y']:.0f}..{b['max_y']:.0f} m"
        )

    print("\nround-trip test (lat/lon -> meters -> lat/lon, must be < 0.01 m):")
    failures = []
    for feature in features:
        lon, lat = feature["properties"]["center_lonlat"]
        error = moon.round_trip_error_m(lon, lat)
        vertex_errors = [
            moon.round_trip_error_m(float(lon_v), float(lat_v))
            for lon_v, lat_v in feature["geometry_lonlat"]["coordinates"][0]
        ]
        max_vertex = max(vertex_errors)
        status = "PASS" if error < 0.01 and max_vertex < 0.01 else "FAIL"
        if status == "FAIL":
            failures.append(feature["properties"]["name"])
        print(
            f"  {status}  {feature['properties']['name'][:52]:52} "
            f"center err {error:.9f} m, vertices max {max_vertex:.9f} m"
        )
    if failures:
        raise AssertionError(f"round-trip failures: {failures}")
    print("all region round trips < 0.01 m")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:  # noqa: BLE001 - report and fail the target
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(1)
